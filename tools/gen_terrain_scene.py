#!/usr/bin/env python3
"""Writes tests/scenes/_terrain_hills.scene, the T1 goldens' world.

Deterministic (closed-form heights and a fixed LCG, no random module) so
re-running it reproduces the committed file byte for byte. One 65 x 65 tile
with 2-unit cells: a valley through the middle, a ridge to the north-east and
a peak to the north-west, coloured by height and slope (grass, earth, rock,
snow), with trees standing on the surface."""
import math
import os

N, CELL, ORIGIN = 65, 2.0, (-64.0, 0.0, -64.0)


def height(x, z):
    """World x, z to height."""
    h = 2.0 * math.sin(x * 0.09) * math.cos(z * 0.07)
    h += 1.2 * math.sin(x * 0.21 + z * 0.13)
    h += 14.0 * math.exp(-((x + 30) ** 2 + (z + 34) ** 2) / 300.0)   # the north-west peak
    h += 7.0 * math.exp(-((x - z - 50) ** 2) / 260.0) * (1.0 if x > 0 else 0.4)  # the ridge
    h -= 3.0 * math.exp(-(x * x) / 120.0)                            # the valley along z
    return h


hs = [[height(ORIGIN[0] + i * CELL, ORIGIN[2] + j * CELL) for i in range(N)] for j in range(N)]


def slope(i, j):
    i0, i1, j0, j1 = max(i - 1, 0), min(i + 1, N - 1), max(j - 1, 0), min(j + 1, N - 1)
    dx = (hs[j][i1] - hs[j][i0]) / ((i1 - i0) * CELL)
    dz = (hs[j1][i] - hs[j0][i]) / ((j1 - j0) * CELL)
    return math.hypot(dx, dz)


def colour(i, j):
    h, s = hs[j][i], slope(i, j)
    if h > 10.5:
        return (0.92, 0.93, 0.96)                  # snow
    if s > 0.55 or h > 7.5:
        return (0.45, 0.42, 0.40)                  # rock
    if h < -1.8:
        return (0.42, 0.34, 0.22)                  # earth on the valley floor
    g = 0.48 + 0.04 * math.sin(i * 0.7) * math.cos(j * 0.5)
    return (0.20, g, 0.16)                         # grass


state = 20261018


def rnd():
    global state
    state = (state * 1103515245 + 12345) % (1 << 31)
    return state / float(1 << 31)


def fmt(v):
    return f"{v:.3f}".rstrip("0").rstrip(".") if v != 0 else "0"


lines = ["# Generated by tools/gen_terrain_scene.py -- do not edit by hand.",
         f"terrain {fmt(ORIGIN[0])} {fmt(ORIGIN[1])} {fmt(ORIGIN[2])}  {fmt(CELL)} {N} {N}  0.2 0.5 0.16"]
for row in hs:
    lines.append("heights " + " ".join(fmt(h) for h in row))
for j in range(N):
    lines.append("colors " + "  ".join(" ".join(fmt(c) for c in colour(i, j)) for i in range(N)))

lines.append("# trees on gentle grass")
placed = 0
while placed < 45:
    i, j = 2 + int(rnd() * (N - 4)), 2 + int(rnd() * (N - 4))
    hgt = 3 + round(3 * rnd())
    if colour(i, j)[0] != 0.20 or slope(i, j) > 0.35:
        continue
    x, z, y = ORIGIN[0] + i * CELL, ORIGIN[2] + j * CELL, hs[j][i]
    leaves = 2.0 + 1.2 * rnd()
    lines.append(f"item cylinder {x:.2f} {y + hgt / 2 - 0.5:.2f} {z:.2f}  0.8 {hgt / 2:.2f} 0.8  0.45 0.30 0.15")
    lines.append(f"item cube {x:.2f} {y + hgt:.2f} {z:.2f}  {leaves:.2f} {leaves:.2f} {leaves:.2f}  0.10 {0.38 + 0.15 * rnd():.3f} 0.10")
    placed += 1

out = os.path.join(os.path.dirname(__file__), "..", "tests", "scenes", "_terrain_hills.scene")
with open(out, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {os.path.normpath(out)} ({len(lines)} lines)")
