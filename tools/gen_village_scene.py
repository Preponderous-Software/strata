#!/usr/bin/env python3
"""Writes tests/scenes/_village_items.scene, the lighting goldens' world.

Deterministic (a fixed LCG, no random module) so re-running it reproduces the
committed file byte for byte. A 12 x 12 grid of BN-style 15-unit ground tiles
with trees, pawns, rocks and a settlement, sized so the shadow cascades have
something to cover from the camera's feet out to the horizon."""
import os

state = 20261018


def rnd():
    global state
    state = (state * 1103515245 + 12345) % (1 << 31)
    return state / float(1 << 31)


lines = ["# Generated by tools/gen_village_scene.py -- do not edit by hand.", "# ground"]
for gz in range(12):
    for gx in range(12):
        x, z = -82.5 + gx * 15, -82.5 + gz * 15
        g = 0.50 + 0.10 * rnd()
        lines.append(f"item cube {x:g} 0 {z:g}  15 1 15  {0.18 + 0.06 * rnd():.3f} {g:.3f} {0.16 + 0.05 * rnd():.3f}")

lines.append("# trees")
for _ in range(70):
    x, z = -85 + 170 * rnd(), -85 + 170 * rnd()
    if abs(x) < 12 and abs(z) < 12:
        continue
    h = 3 + round(4 * rnd())
    leaves = 2.5 + 1.5 * rnd()
    lines.append(f"item cylinder {x:.2f} 0 {z:.2f}  1 {h} 1  0.45 0.30 0.15")
    lines.append(f"item cube {x:.2f} {h - 1} {z:.2f}  {leaves:.2f} {leaves:.2f} {leaves:.2f}  0.10 {0.40 + 0.15 * rnd():.3f} 0.10")

lines.append("# rocks")
for _ in range(30):
    x, z = -85 + 170 * rnd(), -85 + 170 * rnd()
    s = 0.8 + 1.6 * rnd()
    lines.append(f"item sphere {x:.2f} 0.6 {z:.2f}  {s:.2f} {s * 0.7:.2f} {s:.2f}  0.50 0.50 0.52")

lines.append("# a settlement and its pawns")
for i in range(6):
    x, z = -8 + 6 * (i % 3), -8 + 7 * (i // 3)
    lines.append(f"item cube {x} 1.5 {z}  4 2 4  0.65 0.50 0.35")
    lines.append(f"item cube {x} 3 {z}  3.2 1 3.2  0.55 0.20 0.15")
for _ in range(20):
    x, z = -14 + 28 * rnd(), -14 + 28 * rnd()
    lines.append(f"item capsule {x:.2f} 1.5 {z:.2f}  1 1 1  {0.3 + 0.6 * rnd():.3f} 0.25 {0.3 + 0.6 * rnd():.3f}")

out = os.path.join(os.path.dirname(__file__), "..", "tests", "scenes", "_village_items.scene")
with open(out, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {os.path.normpath(out)} ({len(lines)} lines)")
